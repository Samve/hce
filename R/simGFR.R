#' Simulate longitudinal eGFR data and kidney failure events
#'
#' Simulates longitudinal estimated glomerular filtration rate (eGFR) data
#' for active-treatment and control groups. The simulation includes
#' patient-specific eGFR slopes, measurement error, treatment effects,
#' treatment-dependent measurement bias, and time to kidney failure
#' replacement therapy (KFRT).
#'
#' The active-treatment effect is implemented as a combination of an additive
#' effect on the annual eGFR slope and a proportional effect for patients with
#' a negative random slope. The overall treatment effect is specified by
#' `Delta`, while `annual_decline` specifies the annual eGFR decline in the
#' control group.
#'
#' When `sigma = NULL`, the within-patient measurement-error standard deviation
#' is calculated from the predicted eGFR and is allowed to vary over time.
#' Otherwise, the supplied value of `sigma` is used for all observations.
#'
#' The parameter `bias` is an additive measurement bias applied only to
#' postbaseline observations in the active-treatment group. Baseline
#' measurements and all control-group measurements are unaffected by this bias.
#'
#' KFRT event times are generated using patient- and treatment-specific event
#' rates. The event rate depends on the latent eGFR trajectory and is forced
#' to be very low when observed eGFR is above 30 and very high when observed
#' eGFR is 7 or below.
#'
#' Sustained eGFR-based events are evaluated over a one-month confirmation
#' period. When `TTE = TRUE`, the returned `ADET` dataset contains KFRT and
#' eGFR-based events, while the returned `GFR` dataset contains the simulated
#' longitudinal laboratory data. When `TTE = FALSE`, only the `GFR` dataset is
#' returned and no derived event dataset is generated.
#'
#' @param n sample size in the active-treatment group.
#' @param Delta overall treatment effect on annual eGFR decline. Half of this
#'   effect is implemented additively and half proportionally.
#' @param annual_decline annual eGFR decline in the control group.
#' @param n0 sample size in the control group. Defaults to `n`.
#' @param duration_years Duration of follow-up in years.
#' @param Emin lower bound for the simulated baseline eGFR.
#' @param Emax upper bound for the simulated baseline eGFR.
#' @param m number of equally spaced follow-up intervals. The simulation
#'   includes `m + 1` visits, including baseline.
#' @param bias Additive measurement bias applied to postbaseline active-treatment
#'   measurements only.
#' @param Bias  fractional multiplicative bias bias applied to postbaseline active-treatment
#'   measurements only.
#' @param Sigma between-patient standard deviation for the annual eGFR slope.
#' @param sigma within-patient measurement-error standard deviation. If `NULL`,
#'   it is estimated from the predicted eGFR at each visit.
#' @param TTE logical flag indicating whether to derive time-to-event outcomes.
#'   If `TRUE`, the returned list contains both `GFR` and `ADET`. If `FALSE`,
#'   only `GFR` is returned.
#'
#' @return If `TTE = FALSE`, a list containing one component:
#'   \describe{
#'     \item{GFR}{A data frame containing the simulated longitudinal eGFR data,
#'     treatment indicators, baseline values, observed eGFR, change from
#'     baseline, percent change from baseline, event status, and follow-up
#'     time.}
#'   }
#'
#'   If `TTE = TRUE`, a list with two components:
#'   \describe{
#'     \item{GFR}{A data frame containing the simulated longitudinal eGFR data,
#'     treatment indicators, baseline values, observed eGFR, change from
#'     baseline, percent change from baseline, event status, and follow-up
#'     time.}
#'     \item{ADET}{A data frame containing derived KFRT and eGFR-based events.
#'     Event types are identified by `PARAMCD`, including `KFRT`, `E15`, `E57`,
#'     `E50`, `E40`, and `GFR`.}
#'   }
#'
#' @details
#' The treatment-group annual slope is calculated from the control-group slope
#' and the specified overall treatment effect. The additive component is
#' `Delta / 2`, and the proportional component is represented by
#' `Delta / (2 * abs(annual_decline))`.
#'
#' Patient-specific slopes are generated by adding normally distributed
#' between-patient variation with standard deviation `Sigma` to the control
#' annual decline. Measurement error is normally distributed with standard
#' deviation `sigma`, either supplied by the user or calculated as
#' `sqrt(max(0.1, 0.67 * predicted_eGFR))`.
#'
#' The simulated observed eGFR is bounded below at zero after the measurement
#' bias is applied. Percentage changes from baseline are calculated using the
#' observed baseline measurement.
#'
#' When `TTE = TRUE`, sustained eGFR-based events are derived using a one-month
#' confirmation period and combined with KFRT events in the `ADET` dataset.
#' When `TTE = FALSE`, event derivation is skipped.
#'
#' @examples
#' \dontrun{
#' set.seed(2026)
#' 
#' # Set the significance level
#' alpha <- 0.05
#' Ca <- qnorm(1 - alpha / 2)
#' n <- 750
#' 
#' result <- simGFR(
#'   n = n,
#'   Delta = 0.75,
#'   annual_decline = -4,
#'   duration_years = 2,
#'   bias = 0.5,
#'   Bias = 0.01,
#'   Sigma = 4,
#'   Emin = 25,
#'   Emax = 75,
#'   m = 10,
#'   TTE = FALSE
#' )
#' 
#' gfr_data <- result$GFR
#' 
#' # Calculate treatment-group means, standard deviations, and sample sizes
#' # at each analysis day.
#' res <- aggregate(
#'   AVAL ~ TRTP + ADAY,
#'   data = gfr_data,
#'   FUN = function(x) {
#'     c(
#'       mean = mean(x),
#'       sd = sd(x),
#'       n = length(x)
#'     )
#'   }
#' )
#' 
#' res <- cbind(
#'   res[c("TRTP", "ADAY")],
#'   as.data.frame(res$AVAL)
#' )
#' 
#' names(res) <- c("TRTP", "ADAY", "mean", "sd", "n")
#' 
#' # Calculate the 95% confidence interval half-width.
#' res$ci <- Ca * res$sd / sqrt(res$n)
#' 
#' # Separate the active-treatment and control groups.
#' res_A <- res[res$TRTP == "A", ]
#' res_P <- res[res$TRTP == "P", ]
#' 
#' # Define axis values.
#' xrange <- seq(0, 2, by = 0.125)
#' yrange <- seq(0, 100, by = 1)
#' 
#' # Plot the treatment-group means.
#' plot(
#'   mean ~ ADAY,
#'   data = res_A,
#'   type = "b",
#'   col = "blue",
#'   ylim = c(38, 55),
#'   xlab = "Analysis Day",
#'   ylab = "Estimated GFR",
#'   xaxt = "n",
#'   yaxt = "n"
#' )
#' 
#' axis(1, at = xrange, labels = xrange * 360)
#' axis(2, at = yrange, labels = yrange)
#' abline(v = xrange, h = yrange, col = "grey", lty = 3)
#' 
#' points(
#'   mean ~ ADAY,
#'   data = res_P,
#'   type = "b",
#'   col = "red"
#' )
#' 
#' legend(
#'   "topright",
#'   legend = c("A", "P"),
#'   col = c("blue", "red"),
#'   pch = 1,
#'   lty = 1
#' )
#' 
#' # Add 95% confidence interval arrows for the active-treatment group.
#' arrows(
#'   x0 = res_A$ADAY,
#'   y0 = res_A$mean - res_A$ci,
#'   x1 = res_A$ADAY,
#'   y1 = res_A$mean + res_A$ci,
#'   angle = 90,
#'   code = 3,
#'   length = 0.05,
#'   col = "blue"
#' )
#' 
#' # Add 95% confidence interval arrows for the control group.
#' arrows(
#'   x0 = res_P$ADAY,
#'   y0 = res_P$mean - res_P$ci,
#'   x1 = res_P$ADAY,
#'   y1 = res_P$mean + res_P$ci,
#'   angle = 90,
#'   code = 3,
#'   length = 0.05,
#'   col = "red"
#' )
#' 
#' # Add the number of patients at each visit.
#' text(
#'   x = res_A$ADAY,
#'   y = 39.5,
#'   labels = res_A$n,
#'   col = "blue",
#'   cex = 0.8
#' )
#' 
#' text(
#'   x = res_P$ADAY,
#'   y = 38.5,
#'   labels = res_P$n,
#'   col = "red",
#'   cex = 0.8
#' )
#' 
#' # Add group labels to the left of the patient-count annotations.
#' text(
#'   x = par("usr")[1],  # Left edge of the current plotting region
#'   y = 39.5,           # Vertical position of the A-group label
#'   labels = "A:",      # Label text
#'   col = "blue",       # Match the color of group A
#'   pos = 2,            # Place the label to the left of the x-coordinate
#'   xpd = TRUE           # Allow drawing outside the plot region
#' )
#' 
#' text(
#'   x = par("usr")[1],  # Left edge of the current plotting region
#'   y = 38.5,           # Vertical position of the P-group label
#'   labels = "P:",      # Label text
#'   col = "red",        # Match the color of group P
#'   pos = 2,            # Place the label to the left of the x-coordinate
#'   xpd = TRUE           # Allow drawing outside the plot region
#' )
#' }
#'
#' @export
#' @md
#' @seealso [hce::simKHCE()] for a more general implementation with a
#'   derivation of kidney HCE.
simGFR <- function(
    n,
    Delta,
    annual_decline = -4,
    n0 = n,
    duration_years = 2,
    Emin = 20,
    Emax = 100,
    m = 10,
    bias = 0,
    Bias = 0,
    Sigma = 3,
    sigma = NULL,
    TTE = FALSE
) {
  # Fixed KFRT rate parameters used to generate time-to-event outcomes.
  # The active and control baseline rates are equal, so treatment affects
  # KFRT risk through the simulated eGFR trajectory.
  TTE_A <- 1000
  TTE_P <- TTE_A
  theta <- -0.4605
  
  # Retain the first value of scalar simulation parameters.
  Delta <- Delta[1]
  CM_P <- annual_decline[1]
  n <- n[1]
  n0 <- n0[1]
  TTE_A <- TTE_A[1]
  TTE_P <- TTE_P[1]
  fixedfy <- duration_years[1]
  Emin <- Emin[1]
  Emax <- Emax[1]
  sigma <- sigma[1]
  Sigma <- Sigma[1]
  m <- round(m)[1]
  theta <- theta[1]
  bias <- bias[1]
  Bias <- Bias[1]
  TTE <- as.logical(TTE[1])
  # Split the overall treatment effect equally between additive and
  # proportional components.
  delta <- Delta / 2
  CM_A <- delta + CM_P
  phi <- Delta / (2 * abs(CM_P))
  
  # Validate the main simulation parameters.
  stopifnot(
    "The standard deviation `Sigma` should be positive." =
      all(c(Sigma > 0)),
    "GFR range `Emin` and `Emax` should be non-negative and `Emin` < `Emax`." =
      all(c(Emin >= 0, Emax >= 0, Emin < Emax)),
    "`m` must be >= 1" =
      m >= 1,
    "`duration_years` must be positive" =
      fixedfy > 0,
    "The `bias` should be numeric" =
      is.numeric(bias),
    "The proportional `Bias` should be numeric" =
      is.numeric(Bias)
  )
  
  if (!is.null(sigma)) {
    stopifnot(
      "The standard deviation `sigma` must be positive or left `NULL` for data-driven estimates." =
        sigma > 0
    )
  }
  
  N <- n0 + n
  b0 <- CM_P
  b1 <- CM_A - CM_P
  c0 <- log(TTE_P)
  c1 <- log(TTE_A / TTE_P)
  c2 <- theta
  
  # Create patient identifiers and treatment assignments:
  # TRTPN = 1 denotes active treatment and TRTPN = 0 denotes control.
  d <- data.frame(
    ID = 1:N,
    TRTPN = c(rep(1, n), rep(0, n0))
  )
  
  # Generate patient-specific annual eGFR slopes with between-patient
  # variability.
  d$SLOPE <- b0 + stats::rnorm(N, mean = 0, sd = Sigma)
  
  # Apply the proportional component of the treatment effect to active-arm
  # patients with a negative random slope.
  d$SLOPE <- ifelse(
    d$TRTPN == 1 & d$SLOPE < 0,
    d$SLOPE * (1 - phi),
    d$SLOPE
  )
  
  # Apply the additive treatment effect to the active-arm slope.
  d$SLOPE <- d$SLOPE + b1 * d$TRTPN
  
  # Generate latent baseline eGFR values before measurement error is added.
  d$BASE0 <- stats::runif(N, Emin, Emax)
  
  # Generate equally spaced visits, including baseline and the final visit.
  tj <- (0:m) * fixedfy / m
  
  # Generate visits for all patients.
  VISITS <- data.frame(
    ID = rep(1:N, each = m + 1),
    ADAY = rep(tj, times = N)
  )
  
  # Merge visit times with patient-level simulation variables.
  d1 <- merge(VISITS, d, all.x = TRUE, by = "ID")
  
  # Estimate time-dependent measurement-error variability when sigma is NULL.
  if (is.null(sigma)) {
    VAR <- 0.67 * (d1$SLOPE * d1$ADAY + d1$BASE0)
    VAR[VAR <= 0.1] <- 0.1
    sigma <- sqrt(VAR)
  }
  
  # Generate observed baseline 
  BASE <- d1$BASE0 + stats::rnorm(nrow(d1), sd = sigma)
  # Apply additive and proportional measurement biases only to postbaseline active-arm
  # measurements. Baseline measurements and control-arm measurements are
  # unchanged.
  idx <- d1$TRTPN == 1 & d1$ADAY > 0 
  d1$AVAL <- d1$SLOPE * d1$ADAY + ifelse(BASE <= Emin, Emin, 
                                         ifelse(BASE >= Emax, Emax, BASE))
  
  d1$AVAL[idx] <- (1 + Bias)*d1$AVAL[idx] + bias
  
  # Prevent observed eGFR from being negative.
  d1$AVAL[d1$AVAL < 0] <- 0
  
  # Extract the observed baseline measurement for each patient.
  d2 <- d1[d1$ADAY == 0, c("ID", "AVAL")]
  names(d2) <- c("ID", "BASE")
  
  # Generate one patient-specific uniform random variable for KFRT
  # event-time simulation.
  d2$U <- stats::runif(nrow(d2))
  
  # Merge observed baseline variables into the longitudinal dataset.
  d3 <- merge(d1, d2, by = "ID", all.x = TRUE)
  
  # Calculate patient- and treatment-specific KFRT rates from the latent
  # eGFR trajectory.
  d3$RATE0 <- exp(c0 + c1 * d3$TRTPN)
  d3$RATE <- d3$RATE0 *
    exp(c2 * (d3$SLOPE * d3$ADAY + d3$BASE0))
  
  # Apply extreme event rates at observed eGFR thresholds to approximate
  # near-certain KFRT at very low eGFR and near-zero KFRT at high eGFR.
  d3$RATE <- ifelse(
    d3$AVAL > 30,
    1e-06,
    ifelse(d3$AVAL <= 7, 1e+06, d3$RATE)
  )
  
  # Order the data correctly before accumulating the hazard.
  d3 <- d3[order(d3$ID, d3$ADAY), ]
  
  d3$PADY <- fixedfy
  dt <- fixedfy / m
  
  # Calculate cumulative hazard for each patient.
  d3$CUMHAZ <- stats::ave(
    d3$RATE * dt,
    d3$ID,
    FUN = cumsum
  )
  
  d3$V <- -log(d3$U)
  
  # Identify intervals in which KFRT events occur.
  d4 <- d3[d3$V <= d3$CUMHAZ, ]
  
  if (nrow(d4) > 0) {
    # Select the first event for each patient.
    d4 <- d4[order(d4$ID, d4$ADAY), ]
    d4 <- d4[!duplicated(d4$ID), ]
    
    # Calculate the event time within the interval in which the event occurs.
    d4$AVALT <- (
      d4$V - (d4$CUMHAZ - d4$RATE * dt)
    ) / d4$RATE + d4$ADAY
    
    # Protect against numerical rounding beyond the end of follow-up.
    d4$AVALT <- pmin(d4$AVALT, d4$PADY)
    
    d5 <- merge(
      d3,
      d4[, c("ID", "AVALT")],
      all.x = TRUE,
      by = "ID"
    )
    
    # Assign event status and censoring time.
    d5$EVENT <- NA
    d5$EVENT <- ifelse(is.na(d5$AVALT), 0, 1)
    d5[is.na(d5$AVALT), "AVALT"] <- fixedfy
  } else {
    d5 <- d3
    d5$EVENT <- 0
    d5$AVALT <- fixedfy
  }
  
  # Remove intermediate latent and event-rate variables.
  d5[, c("SLOPE", "BASE0", "RATE", "RATE0")] <- NULL
  
  # Calculate absolute and percentage changes from the observed baseline.
  d5$CHG <- d5$AVAL - d5$BASE
  d5$PCHG <- (d5$AVAL / d5$BASE - 1) * 100
  
  # Remove observations after the generated KFRT event.
  d5 <- d5[d5$ADAY <= d5$AVALT, ]
  
  # Sort the longitudinal dataset.
  ADLB <- d5[order(d5$ID, d5$ADAY), ]
  
  # Derive sustained eGFR event indicators.
  d <- ADLB
  if(!TTE){
    data_return <- ADLB
    data_return[, c("CUMHAZ", "V", "U")] <- NULL
    data_return$TRTP <- ifelse(data_return$TRTPN == 1, "A", "P")
    L <- list(
      GFR = data_return
    )
    return(L)
  }
  d$E40 <- ifelse(d$PCHG <= -40, 1, 0)
  d$E50 <- ifelse(d$PCHG <= -50, 1, 0)
  d$E57 <- ifelse(d$PCHG <= -57, 1, 0)
  d$E15 <- ifelse(d$AVAL < 15, 1, 0)
  
  # Identify the first sustained event for a patient and event definition.
  sustained <- function(dat, x) {
    dat <- as.data.frame(dat)
    dat <- dat[order(dat$ADAY), ]
    row.names(dat) <- NULL
    
    thr0 <- as.numeric(substr(x, 2, 3))
    thr <- ifelse(x == "E15", thr0, -thr0)
    
    I <- which(dat[, x] == 1)
    
    if (length(I) == 0) {
      return(NULL)
    }
    
    for (k in 1:length(I)) {
      i <- I[k]
      t0 <- dat[i, "ADAY"]
      t1 <- t0 + 1 / 12
      j <- which(dat$ADAY >= t1)[1]
      
      if (is.na(i) | is.na(j)) {
        next
      }
      
      # Require all measurements during the confirmation window to satisfy
      # the percentage-change criterion.
      if (
        x %in% c("E57", "E50", "E40") &
        all(dat[i:j, "PCHG"] <= thr)
      ) {
        dat0 <- dat[i, c("ID", "ADAY", x)]
        names(dat0) <- c("ID", "ADAY", "EVENT")
        dat0$EVENT <- x
        return(dat0)
      }
      
      # Require all measurements during the confirmation window to satisfy
      # the absolute eGFR criterion.
      if (
        x %in% c("E15") &
        all(dat[i:j, "AVAL"] < thr)
      ) {
        dat0 <- dat[i, c("ID", "ADAY", x)]
        names(dat0) <- c("ID", "ADAY", "EVENT")
        dat0$EVENT <- x
        return(dat0)
      }
    }
    
    return(NULL)
  }
  
  # Identify sustained 40% eGFR decline events.
  l <- lapply(split(d, d$ID), sustained, x = "E40")
  E1 <- do.call(rbind, l)
  
  # Identify sustained 50% eGFR decline events.
  l <- lapply(split(d, d$ID), sustained, x = "E50")
  E2 <- do.call(rbind, l)
  
  # Identify sustained 57% eGFR decline events.
  l <- lapply(split(d, d$ID), sustained, x = "E57")
  E3 <- do.call(rbind, l)
  
  # Identify sustained eGFR below 15 events.
  l <- lapply(split(d, d$ID), sustained, x = "E15")
  E4 <- do.call(rbind, l)
  
  # Store all eGFR-based events before applying event prioritization.
  ADET0 <- rbind(E1, E2, E3, E4)
  
  if (!is.null(ADET0)) {
    names(ADET0) <- c("ID", "AVAL0", "PARAMCD")
  }
  
  # Retain only the most severe applicable eGFR-based event for each patient.
  E3 <- E3[!E3$ID %in% E4$ID, ]
  E2 <- E2[!E2$ID %in% c(E3$ID, E4$ID), ]
  E1 <- E1[!E1$ID %in% c(E2$ID, E3$ID, E4$ID), ]
  
  E <- rbind(E3, E2, E1, E4)
  
  if (!is.null(E)) {
    names(E) <- c("ID", "AVAL0", "PARAMCD")
  }
  
  # Add final change in eGFR for patients without an eGFR-based event.
  d0 <- d[
    !d$ID %in% E$ID & d$ADAY == d$PADY,
    c("ID", "CHG")
  ]
  
  if (nrow(d0) > 0) {
    names(d0) <- c("ID", "AVAL0")
    d0$PARAMCD <- "GFR"
  }
  
  # Combine eGFR-based events with final change in eGFR values.
  d1 <- rbind(d0, E)
  
  # Extract KFRT events.
  d2 <- unique(d[d$EVENT == 1, c("ID", "AVALT")])
  
  if (nrow(d2) > 0) {
    d2$PARAMCD <- "KFRT"
    names(d2) <- c("ID", "AVAL0", "PARAMCD")
  }
  
  # Add KFRT events and remove lower-priority events for the same patients.
  d3 <- rbind(
    d1[!d1$ID %in% d2$ID, ],
    d2
  )
  
  # Add numeric parameter codes.
  PARAM <- data.frame(
    PARAMCD = c("KFRT", "E15", "E57", "E50", "E40", "GFR"),
    PARAMN = 1:6
  )
  
  d4 <- merge(
    d3,
    PARAM,
    by = "PARAMCD",
    all.x = TRUE
  )
  
  d4 <- d4[, c("ID", "PARAMCD", "PARAMN", "AVAL0")]
  d4 <- d4[order(d4$ID), ]
  
  # Retain patient-level treatment and follow-up variables.
  d5 <- unique(d[, c("ID", "TRTPN", "PADY", "BASE")])
  
  d6 <- merge(d5, d4, by = "ID")
  
  # Add treatment labels to the longitudinal GFR dataset.
  ADLB$TRTP <- ifelse(ADLB$TRTPN == 1, "A", "P")
  
  # Combine all derived events with KFRT events.
  ADET <- rbind(ADET0, d2)
  
  if (!is.null(ADET)) {
    ADET <- ADET[order(ADET$ID), ]
  }
  
  # Remove intermediate event-time simulation variables.
  ADLB[, c("U", "CUMHAZ", "V")] <- NULL
  
  # Return the longitudinal GFR dataset and derived event dataset.
  L <- list(
    GFR = ADLB,
    ADET = ADET
  )
  
  return(L)
}